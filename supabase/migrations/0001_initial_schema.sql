-- =====================================================
-- Prediction Markets Bot - Initial Schema
-- =====================================================

create extension if not exists "pgcrypto";

-- =====================================================
-- markets: canonical view of all tradeable markets
-- =====================================================
create table if not exists markets (
  id uuid primary key default gen_random_uuid(),
  platform text not null check (platform in ('polymarket', 'kalshi')),
  external_id text not null,                -- token_id (Polymarket) or ticker (Kalshi)
  question text not null,
  category text,                            -- 'crypto', 'weather', 'sports', 'politics', etc.
  outcome text,                             -- 'YES' / 'NO' for binary
  closes_at timestamptz,
  resolved_at timestamptz,
  resolution text,                          -- 'YES', 'NO', 'CANCELED'
  metadata jsonb default '{}'::jsonb,
  created_at timestamptz default now(),
  updated_at timestamptz default now(),
  unique (platform, external_id, outcome)
);
create index if not exists idx_markets_platform_category on markets(platform, category);
create index if not exists idx_markets_closes_at on markets(closes_at) where resolved_at is null;

-- =====================================================
-- order_book_snapshots: time series of best bid/ask
-- =====================================================
create table if not exists order_book_snapshots (
  id bigserial primary key,
  market_id uuid not null references markets(id) on delete cascade,
  ts timestamptz not null default now(),
  best_bid numeric(10,6),
  best_ask numeric(10,6),
  bid_size numeric(18,6),
  ask_size numeric(18,6),
  mid numeric(10,6),
  raw jsonb
);
create index if not exists idx_obs_market_ts on order_book_snapshots(market_id, ts desc);

-- =====================================================
-- signals: predictions/edges generated by strategies
-- =====================================================
create table if not exists signals (
  id uuid primary key default gen_random_uuid(),
  strategy text not null,
  market_id uuid references markets(id) on delete cascade,
  cross_market_id uuid references markets(id) on delete cascade, -- for arb pairs
  ts timestamptz not null default now(),
  edge_bps integer,                         -- edge in basis points (100 = 1%)
  model_prob numeric(6,5),                  -- model's true probability estimate
  market_prob numeric(6,5),                 -- market's implied probability
  recommended_size_usd numeric(12,2),
  side text check (side in ('YES', 'NO', 'ARB_BUY_BOTH')),
  acted boolean default false,
  reason text,
  payload jsonb
);
create index if not exists idx_signals_strategy_ts on signals(strategy, ts desc);
create index if not exists idx_signals_acted on signals(acted, ts desc);

-- =====================================================
-- orders: every order we sent (or would have sent in paper)
-- =====================================================
create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  signal_id uuid references signals(id),
  market_id uuid not null references markets(id) on delete cascade,
  strategy text not null,
  mode text not null check (mode in ('paper', 'live')),
  side text not null check (side in ('BUY', 'SELL')),
  order_type text not null check (order_type in ('LIMIT', 'MARKET', 'FOK', 'IOC')),
  price numeric(10,6),
  size numeric(18,6) not null,
  outcome text not null check (outcome in ('YES', 'NO')),
  external_order_id text,                   -- platform's order id
  status text default 'pending' check (status in ('pending', 'open', 'filled', 'partial', 'canceled', 'rejected')),
  filled_size numeric(18,6) default 0,
  avg_fill_price numeric(10,6),
  fees numeric(12,6) default 0,
  rebate numeric(12,6) default 0,
  ts_created timestamptz default now(),
  ts_filled timestamptz,
  ts_canceled timestamptz,
  error text,
  raw jsonb
);
create index if not exists idx_orders_market on orders(market_id, ts_created desc);
create index if not exists idx_orders_strategy on orders(strategy, ts_created desc);
create index if not exists idx_orders_status on orders(status) where status in ('pending', 'open', 'partial');

-- =====================================================
-- positions: current open positions (materialized from orders)
-- =====================================================
create table if not exists positions (
  id uuid primary key default gen_random_uuid(),
  market_id uuid not null references markets(id) on delete cascade,
  outcome text not null check (outcome in ('YES', 'NO')),
  strategy text not null,
  size numeric(18,6) not null,              -- positive = long, negative = short
  avg_entry_price numeric(10,6) not null,
  unrealized_pnl numeric(12,4) default 0,
  realized_pnl numeric(12,4) default 0,
  opened_at timestamptz default now(),
  closed_at timestamptz,
  unique (market_id, outcome, strategy)
);
create index if not exists idx_positions_open on positions(strategy) where closed_at is null;

-- =====================================================
-- pnl_daily: daily PnL aggregate (used by risk engine)
-- =====================================================
create table if not exists pnl_daily (
  date date not null,
  strategy text not null,
  mode text not null,
  realized_pnl numeric(12,4) default 0,
  unrealized_pnl numeric(12,4) default 0,
  num_trades integer default 0,
  fees_paid numeric(12,4) default 0,
  rebates_earned numeric(12,4) default 0,
  primary key (date, strategy, mode)
);

-- =====================================================
-- price_feed_cache: external price ticks (Binance, Coinbase, NOAA)
-- Used by latency arb + weather model
-- =====================================================
create table if not exists price_feed_cache (
  id bigserial primary key,
  source text not null,                     -- 'binance', 'coinbase', 'noaa'
  symbol text not null,                     -- 'BTCUSDT', 'NYC_TEMP', etc.
  ts timestamptz not null default now(),
  value numeric(18,8) not null,
  metadata jsonb
);
create index if not exists idx_price_feed_source_symbol_ts on price_feed_cache(source, symbol, ts desc);

-- =====================================================
-- weather_signals: NOAA-derived probabilities for Kalshi
-- =====================================================
create table if not exists weather_signals (
  id uuid primary key default gen_random_uuid(),
  station_id text not null,                 -- 'KNYC', 'KLAX', etc.
  metric text not null,                     -- 'high_temp_f', 'low_temp_f', 'precip_in'
  target_date date not null,
  model text not null,                      -- 'hgefs_v12', 'nbm', 'gfs'
  ensemble_mean numeric(10,4),
  ensemble_std numeric(10,4),
  threshold_probs jsonb,                    -- e.g. {">85F": 0.62, ">90F": 0.31}
  forecast_ts timestamptz default now(),
  unique (station_id, metric, target_date, model, forecast_ts)
);

-- =====================================================
-- view: open positions with current mid price
-- =====================================================
create or replace view v_open_positions as
select
  p.*,
  m.platform,
  m.external_id,
  m.question,
  m.category,
  (
    select obs.mid
    from order_book_snapshots obs
    where obs.market_id = p.market_id
    order by obs.ts desc
    limit 1
  ) as last_mid
from positions p
join markets m on m.id = p.market_id
where p.closed_at is null;
